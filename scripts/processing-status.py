#!/usr/bin/env python3
"""Keep PROCESSING-ROADMAP.md honest, and catch duplicates before they're added.

  python scripts/processing-status.py             # sync every queue, rewrite the status table
  python scripts/processing-status.py --check URL [URL ...]
                                                  # is this link already in the repo? (run BEFORE adding)

What "sync" does:
  1. finds every `podcast-archive/*/00-queue.md`
  2. ticks T (transcript in) and N (notes written) for each row from the file itself:
     a file still showing `*Pending.*` has no transcript; `*Notes pending.*` has no notes
  3. rewrites the status table in PROCESSING-ROADMAP.md between the STATUS markers
  4. reports any YouTube video that appears in more than one archive file

--check looks for a YouTube video ID, playlist ID, @handle, or Google Drive file ID
anywhere in the repo's markdown and says where it already lives.
"""
from __future__ import annotations
import argparse, datetime as dt, re, sys
from collections import defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
ROADMAP = REPO / "PROCESSING-ROADMAP.md"
START, END = "<!-- STATUS:START -->", "<!-- STATUS:END -->"
VID = re.compile(r"(?:youtube\.com/watch\?v=|youtu\.be/|youtube\.com/shorts/)([A-Za-z0-9_-]{11})")

def field(text: str, name: str) -> str:
    m = re.search(rf"\*\*{name}:\*\*\s*(.+?)\s*$", text, re.M)
    return m.group(1).strip() if m else ""

def sync_queue(q: Path) -> dict:
    lines = q.read_text(encoding="utf-8").split("\n")
    tot = t = n = 0
    for i, line in enumerate(lines):
        m = re.search(r"\]\(([^)]+\.md)\) \|\s*$", line)
        if not (m and line.startswith("| ")):
            continue
        f = q.parent / m.group(1)
        if not f.exists():
            continue
        body = f.read_text(encoding="utf-8")
        T = "[ ]" if "\n*Pending.*" in body else "[x]"
        N = "[ ]" if "\n*Notes pending.*" in body else "[x]"
        cells = line.split("|")
        cells[2], cells[3] = f" {T} ", f" {N} "
        lines[i] = "|".join(cells)
        tot += 1; t += T == "[x]"; n += N == "[x]"
    q.write_text("\n".join(lines), encoding="utf-8")
    head = "\n".join(lines[:12])
    title = lines[0].lstrip("# ").replace(": queue", "").strip()
    return {"title": title, "folder": q.parent.name, "contrib": field(head, "Contributed by"),
            "total": tot, "t": t, "n": n}

def status_table(rows: list[dict]) -> str:
    out = [f"*Generated by `python scripts/processing-status.py` on {dt.date.today().isoformat()}. Don't edit by hand.*", "",
           "| Source | Contributed by | Items | Transcripts | Notes | Queue |", "|---|---|---|---|---|---|"]
    for r in rows:
        out.append(f"| {r['title']} | {r['contrib']} | {r['total']} | {r['t']} of {r['total']} | {r['n']} of {r['total']} | "
                   f"[queue](podcast-archive/{r['folder']}/00-queue.md) |")
    return "\n".join(out)

def duplicates() -> dict[str, set[str]]:
    seen = defaultdict(set)
    for f in (REPO / "podcast-archive").rglob("*.md"):
        if f.name == "00-queue.md":
            continue
        # header only: the source line above the first '---'
        head = f.read_text(encoding="utf-8", errors="ignore").split("\n---", 1)[0]
        for v in set(VID.findall(head)):
            seen[v].add(str(f.relative_to(REPO)).replace("\\", "/"))
    return {k: v for k, v in seen.items() if len(v) > 1}

def keys_for(url: str) -> list[str]:
    keys = VID.findall(url)
    keys += re.findall(r"[?&]list=([A-Za-z0-9_-]+)", url)
    keys += re.findall(r"youtube\.com/(@[A-Za-z0-9_.-]+)", url)
    keys += re.findall(r"drive\.google\.com/(?:file/d/|open\?id=|drive/folders/)([A-Za-z0-9_-]{20,})", url)
    keys += re.findall(r"docs\.google\.com/\w+/d/([A-Za-z0-9_-]{20,})", url)
    return keys or [url.strip()]

def check(urls: list[str]) -> int:
    files = [f for f in REPO.rglob("*.md") if ".git" not in f.parts]
    found_any = False
    for url in urls:
        for k in keys_for(url):
            hits = []
            for f in files:
                try:
                    if k.lower() in f.read_text(encoding="utf-8", errors="ignore").lower():
                        hits.append(str(f.relative_to(REPO)).replace("\\", "/"))
                except OSError:
                    pass
            if hits:
                found_any = True
                print(f"ALREADY HERE  {k}  ->  " + ", ".join(sorted(hits)[:5]) + (" ..." if len(hits) > 5 else ""))
            else:
                print(f"NEW           {k}")
    return 1 if found_any else 0

def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", nargs="+", metavar="URL")
    a = ap.parse_args()
    if a.check:
        return check(a.check)
    rows = [sync_queue(q) for q in sorted((REPO / "podcast-archive").glob("*/00-queue.md"))]
    text = ROADMAP.read_text(encoding="utf-8")
    if START in text and END in text:
        pre, rest = text.split(START, 1)
        post = rest.split(END, 1)[1]
        ROADMAP.write_text(f"{pre}{START}\n{status_table(rows)}\n{END}{post}", encoding="utf-8")
    for r in rows:
        print(f"{r['title']}: {r['t']}/{r['total']} transcripts, {r['n']}/{r['total']} notes  ({r['contrib']})")
    d = duplicates()
    print(f"duplicates across archive files: {len(d)}")
    for k, v in d.items():
        print(f"  {k}: {', '.join(sorted(v))}")
    return 0

if __name__ == "__main__":
    sys.exit(main())
